/**
 * Grade provenance audit (physician-reviewer angle): for every grade shown on /pair pages,
 * /drug pages and the desk check row, can a reviewer see WHY in one click?
 * Writes docs/grade-provenance-audit.md.
 *
 *   npx --yes tsx scripts/grade-provenance-audit.ts           # print summary + write
 *   npx --yes tsx scripts/grade-provenance-audit.ts --check   # exit 1 if the md is stale
 *
 * Deterministic (no timestamp). "Before" is the UI on main before feat/grade-provenance:
 *  - pair page: a verbatim quote + DailyMed link was visible only when the page had a quote row;
 *  - drug page: no basis; the grade's quote was two clicks away (open pair page);
 *  - desk check row: one click opened source chips (titles + links) but not the quote text.
 * "After" is computed from the data the new "Why this grade" blocks render.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { pairPages } from "../src/lib/seo/pair-pages.ts";
import { drugHubs } from "../src/lib/seo/drug-hubs.ts";
import { analyze } from "../src/lib/drugs/engine.ts";
import { DRUGS } from "../src/lib/drugs/catalog.ts";
import { gradeBases } from "../src/lib/drugs/grade-provenance.ts";
import { SEVERITY_LABEL, type Finding } from "../src/lib/drugs/types.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outPath = resolve(root, "docs/grade-provenance-audit.md");
const check = process.argv.includes("--check");
const full = !process.argv.includes("--pages-only");

const pages = pairPages();
const labelLinked = (w: { kind: string; href?: string }[]) => w.some((b) => b.kind === "label" && b.href);
const anyLinked = (w: { kind: string; href?: string }[]) => w.some((b) => b.kind !== "rule" && b.href);

let beforePair = 0, afterPairQuote = 0, afterPairSource = 0, ruleOnlyPages = 0;
const question: string[] = [];
const ruleRows: string[] = [];
const mismatch: string[] = [];
for (const p of pages) {
  if (p.quote) beforePair++;
  if (labelLinked(p.why)) afterPairQuote++;
  if (anyLinked(p.why)) afterPairSource++;
  const ruleOnly = p.why.length > 0 && p.why.every((b) => b.kind === "rule");
  if (ruleOnly) {
    ruleOnlyPages++;
    ruleRows.push(`| ${p.nameA} + ${p.nameB} | ${p.severityLabel} | ${p.why[0]!.title} |`);
    if (p.severity === "contraindicated" || p.severity === "major")
      question.push(`- ${p.nameA} + ${p.nameB}: ${p.severityLabel} rests only on the catalog rule${p.quote ? ` (a ${p.quote.labelDrug} quote is on the page, but for a different mechanism than the graded finding)` : ""}.`);
  } else if (p.quote && !labelLinked(p.why)) {
    mismatch.push(`- ${p.nameA} + ${p.nameB}: ${p.severityLabel}; graded finding cites ${p.why.map((b) => b.title).join("; ")}, page quote is ${p.quote.labelDrug} ${p.quote.labelSection}.`);
  }
}

let hubRows = 0, hubAfter = 0;
for (const h of drugHubs()) for (const g of h.groups) for (const r of g.pairs) {
  hubRows++;
  if (r.why && r.why.kind !== "rule" && r.why.href) hubAfter++;
}

// Desk check row: lead basis for every pair finding behind the pair pages.
let deskRows = 0, deskAfterQuote = 0, deskRule = 0;
for (const p of pages) for (const f of analyze([p.drugA, p.drugB]).findings) {
  if (!(f.drugIds.includes(p.drugA) && f.drugIds.includes(p.drugB))) continue;
  deskRows++;
  const w = gradeBases(f);
  if (w[0]!.kind !== "rule" && w[0]!.href) deskAfterQuote++;
  if (w[0]!.kind === "rule") deskRule++;
}

// Whole catalog: Avoid together / Serious concern findings resting only on an engine rule.
const sevRule: Record<string, [number, number]> = { contraindicated: [0, 0], major: [0, 0] };
const ruleBy: Record<string, number> = {};
const ciRule: string[] = [];
if (full) {
  const real = DRUGS.filter((d) => !d.id.startsWith("__"));
  for (let i = 0; i < real.length; i++) for (let j = i + 1; j < real.length; j++) {
    for (const f of analyze([real[i]!.id, real[j]!.id]).findings as Finding[]) {
      const row = sevRule[f.severity];
      if (!row) continue;
      row[0]++;
      const w = gradeBases(f);
      if (w.every((b) => b.kind === "rule")) {
        row[1]++;
        const rule = (f.id.split("__").pop() ?? f.id).replace(/-[a-z0-9]+$/, "");
        ruleBy[`${SEVERITY_LABEL[f.severity]} · ${rule}`] = (ruleBy[`${SEVERITY_LABEL[f.severity]} · ${rule}`] ?? 0) + 1;
        if (f.severity === "contraindicated") ciRule.push(`- ${f.drugIds.map((id) => DRUGS.find((d) => d.id === id)?.name ?? id).join(" + ")} (${rule})`);
      }
    }
  }
}

const pct = (a: number, b: number) => (b ? `${((100 * a) / b).toFixed(1)}%` : "0.0%");
const md = `# Grade provenance audit

Generated by \`scripts/grade-provenance-audit.ts\`. Do not edit by hand; run with \`--check\` in CI.

Question: for each grade a doctor sees, is the FDA label quote (or the stated basis) and its source link one click away?
This audit changes no grade and adds no source. Where nothing is cited, the UI now says "Basis: catalog enzyme rule" (or "catalog rule").

## Pair pages (/pair/...)

| | Before | After |
|---|---|---|
| Pages | ${pages.length} | ${pages.length} |
| Verbatim label quote + DailyMed link visible (0 clicks) | ${beforePair} | ${beforePair} (quote block unchanged) |
| Graded finding's own basis + link shown ("Why this grade", open) | 0 | ${afterPairSource} |
| ...of which a label quote/section with DailyMed link | 0 | ${afterPairQuote} |
| Grade rests only on a catalog rule (shown as such) | not stated | ${ruleOnlyPages} |

## Drug pages (/drug/...)

| | Before | After |
|---|---|---|
| Graded pair rows | ${hubRows} | ${hubRows} |
| Basis + source link in one click | 0 (two clicks, via the pair page) | ${hubAfter} |
| Rows with an honest catalog-rule note instead | 0 | ${hubRows - hubAfter} |

## Desk check row (pairs behind the pair pages)

| | Before | After |
|---|---|---|
| Pair findings | ${deskRows} | ${deskRows} |
| Quote/basis text + link in one click (open the row) | 0 (source chips only; text took a second click) | ${deskAfterQuote} |
| Lead basis is a catalog-rule note | not stated | ${deskRule} |

${full ? `## Whole catalog: grades resting only on an engine rule

| Tier | Findings | Rule-only | Share |
|---|---|---|---|
${(["contraindicated", "major"] as const).map((s) => `| ${SEVERITY_LABEL[s]} | ${sevRule[s]![0]} | ${sevRule[s]![1]} | ${pct(sevRule[s]![1], sevRule[s]![0])} |`).join("\n")}

Top rule-only rules:

| Tier · rule | Findings |
|---|---|
${Object.entries(ruleBy).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, 15).map(([k, n]) => `| ${k} | ${n} |`).join("\n")}

### Avoid together with no cited source (${ciRule.length})

${ciRule.sort().join("\n") || "None."}
` : ""}
## Pair pages a doctor would likely question

Avoid together / Serious concern pages whose tier rests only on the catalog rule:

${question.sort().join("\n") || "None."}

Pages whose label quote is for a different mechanism than the graded finding:

${mismatch.sort().join("\n") || "None."}

## Pair pages resting only on a catalog rule (${ruleRows.length})

| Pair | Tier | Basis shown |
|---|---|---|
${ruleRows.sort().join("\n")}
`;

if (check) {
  const cur = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
  if (cur !== md) {
    console.error("docs/grade-provenance-audit.md is stale. Run: npx --yes tsx scripts/grade-provenance-audit.ts");
    process.exit(1);
  }
  console.log("grade-provenance-audit.md is current.");
} else {
  writeFileSync(outPath, md);
  console.log(`Pair pages ${pages.length}: quote before ${beforePair}; basis+link after ${afterPairSource} (label ${afterPairQuote}); rule-only ${ruleOnlyPages}.`);
  console.log(`Drug rows ${hubRows}: one-click after ${hubAfter}. Desk rows ${deskRows}: one-click after ${deskAfterQuote}, rule ${deskRule}.`);
  if (full) console.log(`Catalog rule-only: CI ${sevRule.contraindicated![1]}/${sevRule.contraindicated![0]}, major ${sevRule.major![1]}/${sevRule.major![0]}.`);
}
