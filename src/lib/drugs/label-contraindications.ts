/**
 * Label-sourced contraindication pins for named CYP pairs.
 *
 * Why this exists: the enzyme rule (`pkSeverity` in engine.ts) grades pairs
 * from perpetrator strength and substrate sensitivity. For a short list of
 * pairs, the FDA-approved label itself lists the combination under
 * Contraindications. Those pairs should read "Avoid together" because the
 * label says so, not only because the enzyme grades happen to line up. When a
 * perpetrator grade is corrected to FDA's table (for example ciprofloxacin as a
 * moderate CYP1A2 inhibitor), the enzyme rule alone can drop a
 * label-contraindicated pair. A pin keeps it at contraindicated.
 *
 * Scope rules:
 * - Only exact, named catalog pairs. No class expansion, no global threshold
 *   change. Each pin names one enzyme and one direction (inhibitor or inducer).
 * - `quote`, `labelExample`, `labelSection` and `url` are copied byte-for-byte
 *   from `src/lib/drugs/reference/label-gold-set.ts` (PR #65), so the desk and
 *   the gold-set test cite identical text. Quotes are verbatim DailyMed SPL
 *   text ("…" marks an elided span), retrieved 2026-09-27.
 * - Rows with origin "wave3" copy the same fields byte-for-byte from PR #75
 *   (`feat/label-gold-wave3`, commit f41256d). Those quotes were retrieved
 *   2026-10-02. They pin pairs that already produce a CYP3A4 finding below
 *   contraindicated.
 * - Rows with origin "wave4" copy the same fields byte-for-byte from PR #86
 *   (`feat/label-gold-wave4`, commit 5912f77). Those quotes were retrieved
 *   2026-10-02. They hold an existing enzyme finding (below contraindicated
 *   on main) at contraindicated. One enzyme and one direction, the finding
 *   the pair already produces.
 * - Rows with origin "no-enzyme" copy the same fields from the wave-3 or
 *   wave-4 gold set and omit `enzyme` and `kind`. The desk emits a standalone
 *   contraindicated finding and does not invent a CYP grade. Wave 3 is the
 *   seven pairs whose partner has no CYP role the engine uses (elbasvir/
 *   grazoprevir, irinotecan, drospirenone; irinotecan is UGT1A1, not a CYP).
 *   Wave 4 adds pairs that show no enzyme finding: itraconazole with
 *   dofetilide and irinotecan, Kaletra with elbasvir/grazoprevir, and
 *   Paxlovid with flecainide, phenytoin, rifapentine, and the inducers whose
 *   only row today is a washout clock.
 * - Rows with origin "restored-after-58" are not in the gold set. Their quotes
 *   reuse gold-set strings where the same label sentence applies, or are the
 *   verbatim DailyMed Contraindications text (Ranexa section 4).
 * - `contraindicationsSentence` is added only where the gold-set quote comes
 *   from a section other than Contraindications (Zanaflex 7.1, Ranexa 7.1). It
 *   is the verbatim section 4 sentence from the same DailyMed label.
 * - Leftover wave-1 gold pairs (still below contraindicated after the wave-4
 *   pins) copy `quote`, `labelSection`, and the DailyMed link byte-for-byte
 *   from label-gold-set.ts as of a79b09b. Each pin names the enzyme finding
 *   the pair already produces.
 * - Rows with origin "pd" copy quote, labelDrug, labelSection, and the
 *   DailyMed link from the wave-2 gold rows (retrieved 2026-09-27). They omit
 *   enzyme and kind. The desk holds the existing pharmacodynamic finding at
 *   contraindicated. It does not add a CYP grade and it does not add a second
 *   card. Naltrexone is pinned with methadone, buprenorphine, oxycodone, or
 *   hydrocodone only. Wave 5 Geodon pairs use the same path when a
 *   pharmacodynamic card already exists, and the no-enzyme path when none
 *   does. Other naltrexone + opioid pairs are not pinned.
 *
 * Educational reference, not FDA-cleared. No doses.
 */
import type { Enzyme } from "./types";

export interface LabelContraindication {
  /** Stable id, `labelDrugId+otherId` (matches the gold-set id). */
  id: string;
  /** Catalog id of the drug whose label carries the contraindication. */
  labelDrugId: string;
  /** Catalog id of the other drug (the CYP perpetrator). */
  otherId: string;
  /**
   * Enzyme the pinned finding is on. Omitted when there is no enzyme finding
   * to hold. Origin "no-enzyme" then emits a standalone contraindicated
   * finding. Origin "pd" holds the existing pharmacodynamic finding instead.
   * Neither assigns a CYP grade.
   */
  enzyme?: Enzyme;
  /** Direction of the perpetrator on that enzyme. Omitted together with `enzyme`. */
  kind?: "inhibitor" | "inducer";
  labelDrug: string;
  labelSection: string;
  quote: string;
  labelExample?: string;
  contraindicationsSentence?: string;
  url: string;
  /**
   * `named`: the label names this drug (in the Contraindications sentence or
   * the example list it points to). `class`: the Contraindications sentence
   * covers a class this drug belongs to (for example "inducers of CYP3A") but
   * does not name it.
   */
  basis: "named" | "class";
  /** Why the pin was added: gold-set pair from PR #65 (including leftover wave-1 pairs pinned later), restored after PR #58 grade changes, a #75 wave-3 pair that still read below contraindicated, a #86 wave-4 pair whose existing enzyme finding is held at contraindicated, a pair with no enzyme finding to hold, or a pharmacodynamic finding held at contraindicated (naltrexone with a labeled opioid). */
  origin: "gold-set" | "restored-after-58" | "wave3" | "wave4" | "no-enzyme" | "pd";
  /**
   * DailyMed retrieval date for this quote when it is not
   * `LABEL_CONTRAINDICATIONS_RETRIEVED` (wave 3 is 2026-10-02).
   */
  retrieved?: "2026-10-02" | "2026-10-03";
}

