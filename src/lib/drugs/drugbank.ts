/** DrugBank accessions and primary targets. Identity only — CYP scoring stays on this desk. */

export interface BankCard {
  accession: string;
  extra?: string[];
  targets: string[];
  group: "Approved" | "Investigational" | "Illicit" | "Vet" | "Nutraceutical" | "Withdrawn";
}

function b(
  accession: string,
  targets: string[],
  group: BankCard["group"] = "Approved",
  extra?: string[],
): BankCard {
  return extra ? { accession, extra, targets, group } : { accession, targets, group };
}

